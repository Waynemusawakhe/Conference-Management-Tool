import React from "react";
import { it, expect, vi, beforeEach } from "vitest";
import { render, screen, fireEvent, waitFor, within } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import ContactMessagesPage from "../pages/AdminContactMessagesPage";
import { contactMessagesApi } from "../api/contactMessagesApi";
vi.mock("../components/AdminLayout", () => ({ default: ({ children }) => <div>{children}</div> }));
vi.mock("../api/contactMessagesApi", () => ({ contactMessagesApi: { getAll: vi.fn(), remove: vi.fn() } }));
const message = (id, status = "new") => ({ id, name: `Sender ${id}`, email: `sender${id}@example.com`, message: `Message ${id}`, status });
const response = (page, total, data) => ({ data, meta: { current_page: page, last_page: Math.max(1, Math.ceil(total / 25)), total, per_page: 25 } });
beforeEach(() => { vi.restoreAllMocks(); contactMessagesApi.remove.mockResolvedValue({}); });
it("returns to the valid previous page after deleting the only message on the last page", async () => {
  let total = 26;
  contactMessagesApi.getAll.mockImplementation(({ page }) => Promise.resolve(response(page, total, page === 1 ? Array.from({ length: 25 }, (_, i) => message(i + 1)) : total === 26 ? [message(26)] : [])));
  contactMessagesApi.remove.mockImplementation(async () => { total = 25; });
  vi.spyOn(window, "confirm").mockReturnValue(true);
  render(<MemoryRouter><ContactMessagesPage /></MemoryRouter>);
  await screen.findByText("Sender 1");
  fireEvent.click(screen.getByRole("button", { name: "Next" }));
  await screen.findByText("Sender 26");
  fireEvent.click(screen.getByRole("button", { name: "Delete message" }));
  await screen.findByText("Sender 1");
  expect(screen.getByRole("navigation", { name: "Contact message pages" })).toHaveTextContent("Page 1 of 1 · 25 messages");
  expect(contactMessagesApi.remove).toHaveBeenCalledWith(26);
  expect(contactMessagesApi.getAll).toHaveBeenLastCalledWith({ page: 1, per_page: 25, status: undefined });
});
it("explicitly scopes summary counts to the current status-filtered page", async () => {
  contactMessagesApi.getAll.mockImplementation(({ page, status }) => Promise.resolve(response(page, status ? 30 : 50, status ? [message(1)] : [message(1), message(2, "in_progress"), message(3, "resolved")])));
  render(<MemoryRouter><ContactMessagesPage /></MemoryRouter>);
  await screen.findByText("Sender 3");
  const summary = screen.getByRole("region", { name: "Current page message counts" });
  expect(summary).toHaveTextContent("Counts for the current page · Status: All");
  expect(within(summary).getByText("On this page").previousElementSibling).toHaveTextContent("3");
  fireEvent.click(screen.getByRole("button", { name: /^New/ }));
  await waitFor(() => expect(screen.queryByText("Sender 3")).not.toBeInTheDocument());
  const filteredSummary = screen.getByRole("region", { name: "Current page message counts" });
  expect(filteredSummary).toHaveTextContent("Counts for the current page · Status: New");
  expect(within(filteredSummary).getByText("On this page").previousElementSibling).toHaveTextContent("1");
  expect(within(filteredSummary).getByText("In progress").previousElementSibling).toHaveTextContent("0");
  expect(screen.getByRole("navigation", { name: "Contact message pages" })).toHaveTextContent("30 messages");
});
